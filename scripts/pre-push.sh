#!/usr/bin/env bash
# The pre-push hook (root package.json, simple-git-hooks): `pnpm test` on the commit each pushed ref points to, never
# on the working tree. An uncommitted, half-written file can then neither block the push of verified commits nor hide
# a broken one: the suite runs on what the remote will receive. Only those tip commits are tested, not every commit
# between the remote's ref and them.
#
# Git passes one line per ref on stdin: `<local ref> <local sha> <remote ref> <remote sha>`. Each distinct tip commit
# (a deleted ref is skipped, a tag is peeled to its commit) is checked out with `git worktree add --detach` in a
# fresh temporary directory, and there:
#   - the installed node_modules (root and extension/) are linked in. pnpm's links inside them are relative to where
#     they really live, so they still resolve. The pushed commit's pnpm-lock.yaml must equal the one those modules
#     were installed from, or the hook stops: a commit is never reported tested against dependencies it does not pin;
#   - extension/.wxt is generated by `wxt prepare` (its tsconfig paths are relative, so a link would point back at
#     the working tree's sources);
#   - `pnpm test` runs (the unit suite, then the perf pass).
# The temporary worktree is always removed (trap, also on Ctrl-C). The user's working tree and index are never
# touched: GIT_DIR, GIT_INDEX_FILE and the like are cleared first, and the checkout runs with hooks off. One line
# names each commit tested and the result; the exit status is non-zero when any pushed commit fails.
#
# By hand: `bash scripts/pre-push.sh [<rev>...]` tests the given revisions (HEAD when none is given and stdin is a
# terminal). Skip once with `git push --no-verify`.
set -euo pipefail

TAG='pre-push'
TOP=''
SRC=''
TMP_ROOT=''
WORKTREE=''

say() { printf '%s: %s\n' "$TAG" "$*"; }
die() {
  say "$*" >&2
  exit 1
}

# Removes the temporary worktree: the node_modules links first (so nothing below can follow them into the installed
# modules), then the worktree and its admin entry, then the temporary directory.
cleanup() {
  if [ -n "$WORKTREE" ]; then
    rm -f "$WORKTREE/node_modules" "$WORKTREE/extension/node_modules" 2>/dev/null || true
    git -C "$TOP" worktree remove --force "$WORKTREE" >/dev/null 2>&1 || true
    WORKTREE=''
  fi
  if [ -n "$TMP_ROOT" ]; then
    rm -rf "$TMP_ROOT" || true
    TMP_ROOT=''
  fi
  if [ -n "$TOP" ]; then git -C "$TOP" worktree prune >/dev/null 2>&1 || true; fi
}
trap cleanup EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

# The commit a revision names, or nothing when it names no commit (a tag on a tree, say).
commit_of() { git -C "$TOP" rev-parse --verify --quiet "$1^{commit}" 2>/dev/null || true; }

# Appends a commit to the space-separated $COMMITS once.
add_commit() {
  case " $COMMITS " in
    *" $1 "*) ;;
    *) COMMITS="${COMMITS:+$COMMITS }$1" ;;
  esac
}

# The commits to test: the revisions named as arguments, else HEAD at a terminal, else the refs git pushes (stdin).
collect_commits() {
  COMMITS=''
  local rev commit local_ref local_sha remote_ref remote_sha
  if [ "$#" -gt 0 ]; then
    for rev in "$@"; do
      commit="$(commit_of "$rev")"
      [ -n "$commit" ] || die "'$rev' names no commit"
      add_commit "$commit"
    done
  elif [ -t 0 ]; then
    add_commit "$(commit_of HEAD)"
  else
    while read -r local_ref local_sha remote_ref remote_sha || [ -n "${local_ref:-}" ]; do
      [ -n "${local_ref:-}" ] || continue
      # A deleted ref pushes no commit: its local sha is all zeros.
      case "${local_sha:-0}" in *[!0]*) ;; *) continue ;; esac
      commit="$(commit_of "$local_sha")"
      if [ -z "$commit" ]; then
        say "skipped $local_ref: it names no commit"
        continue
      fi
      add_commit "$commit"
    done
  fi
}

# The checkout whose node_modules the tests use: this one, else the main worktree (a push from a linked worktree).
find_installed() {
  local common candidate
  common="$(cd "$(git -C "$TOP" rev-parse --git-common-dir)" && pwd -P)"
  for candidate in "$TOP" "$(dirname "$common")"; do
    if [ -d "$candidate/node_modules" ] && [ -d "$candidate/extension/node_modules" ]; then
      SRC="$candidate"
      return 0
    fi
  done
  die "no installed node_modules in $TOP; run pnpm install, then push again"
}

# Stops when the commit pins other dependencies than the installed ones (pnpm keeps the lockfile it installed from).
check_lockfile() {
  local installed="$SRC/node_modules/.pnpm/lock.yaml"
  [ -f "$installed" ] || die "node_modules in $SRC has no install record; run pnpm install, then push again"
  if ! git -C "$TOP" show "$1:pnpm-lock.yaml" 2>/dev/null | cmp -s - "$installed"; then
    die "$(short "$1") pins other dependencies than the installed node_modules (pnpm-lock.yaml differs); run pnpm install on that commit's lockfile, then push again"
  fi
}

short() { git -C "$TOP" rev-parse --short "$1"; }
subject() { git -C "$TOP" log -1 --format=%s "$1"; }

# Checks the commit out in a fresh temporary worktree, ready for `pnpm test`.
prepare_worktree() {
  TMP_ROOT="$(mktemp -d "${TMPDIR:-/tmp}/attest-pre-push.XXXXXX")"
  # The real path: macOS's $TMPDIR is behind a symlink, and a tool comparing paths must see one spelling.
  TMP_ROOT="$(cd "$TMP_ROOT" && pwd -P)"
  WORKTREE="$TMP_ROOT/worktree"
  git -C "$TOP" -c core.hooksPath=/dev/null worktree add --detach --quiet "$WORKTREE" "$1" ||
    die "could not check out $(short "$1") in a temporary worktree"
  [ -d "$WORKTREE/extension" ] || die "$(short "$1") has no extension/ directory"
  # Installed and generated directories are never committed. One that is (a tracked symlink to the installed
  # node_modules, say) would make `ln` or `wxt prepare` write through it into the user's checkout, so the hook stops.
  local generated
  for generated in node_modules extension/node_modules extension/.wxt; do
    if [ -e "$WORKTREE/$generated" ] || [ -L "$WORKTREE/$generated" ]; then
      die "$(short "$1") tracks $generated, which is installed or generated, never committed; remove it from the commit, then push again"
    fi
  done
  ln -s "$SRC/node_modules" "$WORKTREE/node_modules"
  ln -s "$SRC/extension/node_modules" "$WORKTREE/extension/node_modules"
  if ! (cd "$WORKTREE/extension" && pnpm exec wxt prepare) >"$TMP_ROOT/wxt-prepare.log" 2>&1; then
    cat "$TMP_ROOT/wxt-prepare.log" >&2
    die "wxt prepare failed on $(short "$1")"
  fi
}

# Tests one commit; exits non-zero when its suite does not pass (a failure, or Ctrl-C during the run).
test_commit() {
  local label status=0
  label="$(short "$1") ($(subject "$1"))"
  check_lockfile "$1"
  prepare_worktree "$1"
  say "testing commit $label in a temporary worktree, not the working tree"
  (cd "$WORKTREE" && pnpm test) || status=$?
  cleanup
  if [ "$status" -ne 0 ]; then
    say "pnpm test did not pass on commit $label (exit $status); push blocked"
    exit 1
  fi
  say "pnpm test passed on commit $label"
}

main() {
  TOP="$(git rev-parse --show-toplevel)"
  cd "$TOP"
  # Nothing below may reach the user's index or working tree through an inherited git variable.
  unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_PREFIX GIT_COMMON_DIR GIT_OBJECT_DIRECTORY
  unset GIT_ALTERNATE_OBJECT_DIRECTORIES
  collect_commits "$@"
  if [ -z "$COMMITS" ]; then
    say "nothing to test: no commit is being pushed"
    return 0
  fi
  find_installed
  local commit
  for commit in $COMMITS; do
    test_commit "$commit"
  done
}

main "$@"
