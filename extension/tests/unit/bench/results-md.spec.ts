/**
 * RESULTS.md is generated, never edited by hand (Hard Rule 12; sprint_7 7.0): it is exactly what `pnpm bench` renders
 * from the newest result file of each bench in bench/results (bench/results.ts), and it names that command at its top.
 * CI runs this with the unit tests, so a hand edit fails, and so does a result file committed without the RESULTS.md it
 * makes. Re-running the benches themselves is `pnpm bench`'s, on a quiet machine; this checks what they committed.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import { latestResults, render } from '../../../../bench/results';

const REPO_ROOT = path.resolve(import.meta.dirname, '../../../..');
const RESULTS_MD = readFileSync(path.join(REPO_ROOT, 'RESULTS.md'), 'utf8');

describe('RESULTS.md', () => {
  it('is exactly what bench/results renders', () => {
    expect(RESULTS_MD).toBe(render(latestResults(path.join(REPO_ROOT, 'bench', 'results'))));
  });

  it('names the command that generates it at its top', () => {
    expect(RESULTS_MD.split('\n').slice(0, 3).join('\n')).toContain('Generated by `pnpm bench`');
  });
});
