/**
 * The inputs the advisory model's bench asks a model about (sprint_5 5.5), written to
 * entrypoints/model-check/bench-inputs.json from the labelled corpus (tests/unit/intel/corpus.ts `askedInputs`): one
 * entry per distinct input, keyed by its hash, in case order. The model-check page and bench/intel-record.ts record a
 * model's answers to them. Run `pnpm exec tsx tests/tools/intel-inputs.ts` from extension/ after changing the corpus;
 * tests/unit/intel/bench-inputs.spec.ts fails until the file holds what the corpus asks.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import type { IntelInput } from '../../src/intel/input';
import { askedInputs } from '../unit/intel/corpus';

export const BENCH_INPUTS_FILE = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '../../entrypoints/model-check/bench-inputs.json',
);

const NOTE =
  "The inputs the advisory model's bench asks a model about (sprint_5 5.5): one per distinct input the labelled corpus (tests/fixtures/intel/corpus.json) would have the service worker send, keyed by its hash. Generated by tests/tools/intel-inputs.ts, never edited by hand. The model-check page and bench/intel-record.ts record a model's answers to them. Every value is invented.";

/** The file's content: the note and each distinct asked input with its hash. */
export async function benchInputs(): Promise<{
  note: string;
  inputs: { hash: string; input: IntelInput }[];
}> {
  const inputs: { hash: string; input: IntelInput }[] = [];
  for (const { hash, input } of await askedInputs()) {
    if (!inputs.some((entry) => entry.hash === hash)) inputs.push({ hash, input });
  }
  return { note: NOTE, inputs };
}

const invokedAs = process.argv[1];
if (invokedAs !== undefined && import.meta.url === pathToFileURL(path.resolve(invokedAs)).href) {
  writeFileSync(BENCH_INPUTS_FILE, `${JSON.stringify(await benchInputs(), null, 2)}\n`);
  console.log(`wrote ${path.relative(process.cwd(), BENCH_INPUTS_FILE)}`);
}
