/**
 * `pnpm bench` — the one command that produces RESULTS.md (Hard Rule 12).
 *
 * Every bench writes a JSON file to bench/results/<name>-<yyyy-mm-dd>.json. This script runs the
 * registered benches, then regenerates RESULTS.md from the newest result file of each bench.
 * RESULTS.md is generated, never hand-edited.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const BENCH_DIR = path.dirname(fileURLToPath(import.meta.url));
const RESULTS_DIR = path.join(BENCH_DIR, 'results');
const RESULTS_MD = path.join(BENCH_DIR, '..', 'RESULTS.md');

interface BenchResult {
  readonly bench: string;
  readonly date: string;
  readonly command: string;
  readonly metrics: Readonly<Record<string, number | string | boolean>>;
}

/** Benches register here as later sprints add them (core perf, observers, adapters, intel, red team). */
const BENCHES: readonly { readonly name: string; run(): Promise<void> }[] = [];

function latestResults(): BenchResult[] {
  const files = readdirSync(RESULTS_DIR).filter((file) => file.endsWith('.json'));
  const newest = new Map<string, string>();
  for (const file of files.sort()) {
    const match = /^(.+)-(\d{4}-\d{2}-\d{2})\.json$/.exec(file);
    if (match?.[1] !== undefined) newest.set(match[1], file);
  }
  return [...newest.values()].map(
    (file) => JSON.parse(readFileSync(path.join(RESULTS_DIR, file), 'utf8')) as BenchResult,
  );
}

function render(results: readonly BenchResult[]): string {
  const lines = [
    '# RESULTS',
    '',
    '> Generated by `pnpm bench` from `bench/results/*.json`. Do not edit by hand (Hard Rule 12).',
    '',
  ];
  if (results.length === 0) {
    lines.push(
      'No benchmark results yet. Benches are added from Sprint 1 onward; no number is reported until it is measured.',
      '',
    );
    return lines.join('\n');
  }
  for (const result of results) {
    lines.push(
      `## ${result.bench}`,
      '',
      `Measured ${result.date} with \`${result.command}\`.`,
      '',
      '| Metric | Value |',
      '|---|---|',
    );
    for (const [metric, value] of Object.entries(result.metrics))
      lines.push(`| ${metric} | ${String(value)} |`);
    lines.push('');
  }
  return lines.join('\n');
}

for (const bench of BENCHES) await bench.run();
writeFileSync(RESULTS_MD, render(latestResults()));
console.log(`RESULTS.md regenerated (${String(BENCHES.length)} benches registered).`);
